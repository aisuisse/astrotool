export const dictionaries: Record<Lang, Record<Key, string>> = { en, de };
export type MsgCode = { [K in Key]: K extends `msg.${infer C}` ? C : never }[Key];

/** Sprachneutrale Meldung für Engine/Worker: "@code|arg0|arg1". */
export function msg(code: MsgCode, ...args: (string | number)[]): string {
  return ["@" + code, ...args.map(String)].join("|");
}

export function format(template: string, args: (string | number)[]): string {
  return template.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ""));
}

export function t(lang: Lang, key: Key, ...args: (string | number)[]): string {
  return format(dictionaries[lang][key] ?? dictionaries.en[key] ?? key, args);
}

/** Übersetzt Text aus Engine/Worker. Normaler Text bleibt unverändert. */
export function tr(lang: Lang, text: string | undefined): string {
  if (!text || !text.startsWith("@")) return text ?? "";
  const [code, ...args] = text.slice(1).split("|");
  const key = `msg.${code}` as Key;
  return key in en ? t(lang, key, ...args) : text;
}

export function isLang(v: unknown): v is Lang {
  return v === "en" || v === "de";
}

export type I18nKey = Key;
